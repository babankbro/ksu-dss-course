def rank_splits(data):
    rows = []
    for name, fn in CANDIDATES.items():
        r = info_gain(data, fn(data))
        if r:
            rows.append({"เงื่อนไข": name, **r})
    return (pd.DataFrame(rows).set_index("เงื่อนไข")
            .sort_values("gain", ascending=False))


