# %% [task]
# ### 🧑‍💻 งานที่ 7 (เขียนเป็นข้อความ)
#
# เขียนข้อเสนอความยาวไม่เกินหนึ่งหน้าถึงผู้บริหาร ประกอบด้วย
#
